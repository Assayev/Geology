def run(p, t, bold=False, italic=False, size=None):
    r = p.add_run(t); r.bold, r.italic = bold, italic
    r.font.name = "Times New Roman"; r.font.size = Pt(size or FS)
    r._r.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "Times New Roman")
    return r

def par(parts=(), align=A.JUSTIFY, indent=1.25, before=0, after=3, keep=False):
    p = d.add_paragraph(); p.alignment = align
    f = p.paragraph_format; f.space_before, f.space_after = Pt(before), Pt(after)
    f.line_spacing = 1.0; f.first_line_indent = Cm(indent); f.keep_with_next = keep
    for x in ([parts] if isinstance(parts, str) else parts):
        run(p, *x) if isinstance(x, tuple) else run(p, x)
    return p

